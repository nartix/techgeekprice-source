import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

function assertLocalReferences(value) {
  if (!value || typeof value !== "object") return;
  for (const [key, child] of Object.entries(value)) {
    if (
      key === "$ref" &&
      (typeof child !== "string" || !child.startsWith("#/"))
    ) {
      throw new Error(
        "OpenAPI references must be local fragment references; external access is disabled.",
      );
    }
    assertLocalReferences(child);
  }
}

export async function generate({ schemaPath, outputPath, check = false }) {
  const source = await readFile(schemaPath, "utf8");
  const schema = JSON.parse(source);
  assertLocalReferences(schema);
  const hash = createHash("sha256").update(source).digest("hex");
  const ast = await openapiTS(schema, { alphabetize: true });
  const generated = `// Generated by openapi-typescript. Do not edit.\n// Schema SHA-256: ${hash}\n\n${astToString(ast)}`;
  if (check) {
    const current = await readFile(outputPath, "utf8").catch((error) => {
      if (error.code === "ENOENT") return null;
      throw error;
    });
    if (current !== generated)
      throw new Error(
        "Generated OpenAPI contracts are out of date. Run pnpm --filter @tgp/contracts generate.",
      );
    return;
  }
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generated);
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    await generate({
      schemaPath: fileURLToPath(
        new URL("../openapi/spring.openapi.json", import.meta.url),
      ),
      outputPath: fileURLToPath(
        new URL("../src/generated/spring.ts", import.meta.url),
      ),
      check: process.argv.includes("--check"),
    });
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
